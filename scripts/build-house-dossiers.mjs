/**
 * Everything written about one house, as a reading list.
 *
 * `INDEX.md` answers "where is this rule written down?". This answers a
 * different question, and it is the one that actually comes up: **what do we
 * know about the house standing in front of the player?** A house is the unit
 * this world is organised around and the unit a run collides with, and its
 * material is spread across a catalog entry, a member roll, a grant chain, a
 * relationship table, two or three docs and a handful of design constants -
 * none of which name each other.
 *
 * POINTERS, NEVER CONTENT. This file copies nothing. Copying would create
 * thirty-five new places for a fact to drift out of agreement with itself,
 * which is the defect the whole discoverability effort exists to close - and
 * `docs/world/INDEX.md` says so in as many words: an index shows where a thing
 * is, it does not restate it.
 *
 * Run: node scripts/build-house-dossiers.mjs   (npm run docs:houses)
 *      node scripts/build-house-dossiers.mjs --check
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = path.join(ROOT, 'docs', 'world');
const CATALOG = path.join(ROOT, 'src', 'data', 'cultivation');
const OUT = path.join(DOCS, 'BY-HOUSE.md');

/** id and display name, read off the catalog rather than listed here. */
function houses() {
    const src = fs.readFileSync(path.join(CATALOG, 'sects.ts'), 'utf8');
    const lines = src.split('\n');
    const re = /id: '((?:sect|house)-[a-z0-9-]+)',[\s\S]{0,400}?name: '([^']+)'/g;
    const found = [];
    let m;
    while ((m = re.exec(src))) {
        const line = src.slice(0, m.index).split('\n').length;
        found.push({ id: m[1], name: m[2], line });
    }
    // A house can be declared twice (an entry and a relationship row); the
    // first is the entry, which is the one somebody wants to read.
    const seen = new Set();
    return found.filter(h => !seen.has(h.id) && seen.add(h.id));
}

function corpus() {
    const files = [];
    for (const [dir, rel] of [[DOCS, 'docs/world'], [CATALOG, 'src/data/cultivation']]) {
        for (const name of fs.readdirSync(dir)) {
            if (!/\.(md|ts)$/.test(name)) continue;
            if (name === 'BY-HOUSE.md' || name === 'INDEX.md') continue;
            files.push({ rel: `${rel}/${name}`, base: name, dir: rel,
                         text: fs.readFileSync(path.join(dir, name), 'utf8') });
        }
    }
    return files;
}

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function build() {
    const all = corpus();
    const rows = houses().map(house => {
        const byName = new RegExp(esc(house.name), 'g');
        const byId = new RegExp(esc(house.id), 'g');
        const mentions = [];
        for (const file of all) {
            const n = (file.text.match(byName) || []).length + (file.text.match(byId) || []).length;
            if (n > 0) mentions.push({ rel: file.rel, base: file.base, dir: file.dir, n });
        }
        mentions.sort((a, b) => b.n - a.n || a.rel.localeCompare(b.rel));

        // Design constants whose own block names this house.
        // Ranked by how much of the block is about this house, not merely
        // whether the name appears in it. Thirty-four constants listed flat is
        // the same wall this file exists to take down.
        const constants = new Map();
        for (const file of all) {
            if (!file.rel.endsWith('.ts')) continue;
            const re = /export const ([A-Z][A-Z0-9_]{3,}) *(?::[^=]+)?= *[{[]/g;
            let c;
            while ((c = re.exec(file.text))) {
                const block = file.text.slice(c.index, c.index + 2500);
                byName.lastIndex = 0; byId.lastIndex = 0;
                const n = (block.match(byName) || []).length + (block.match(byId) || []).length;
                if (n > 0) constants.set(c[1], Math.max(constants.get(c[1]) ?? 0, n));
            }
        }
        const ranked = [...constants.entries()]
            .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
        return { ...house, mentions, ranked };
    });

    const spread = rows.map(r => r.mentions.length).sort((a, b) => a - b);
    const median = spread[Math.floor(spread.length / 2)] ?? 0;
    const worst = rows.reduce((a, b) => (b.mentions.length > a.mentions.length ? b : a), rows[0]);

    const lines = [
        '<!-- tier: 2 trigger="somebody needs everything the repo holds about one house" -->',
        '',
        '# What is written about each house',
        '',
        '<!-- Generated by scripts/build-house-dossiers.mjs. Run `npm run docs:houses`. -->',
        '',
        '**A reading list, not a summary.** Nothing here is copied from anywhere, on purpose:',
        'a copy is a second place for a fact to drift, and [`INDEX.md`](INDEX.md) is explicit',
        'that an index shows where a thing is rather than restating it.',
        '',
        '`INDEX.md` answers *where is this rule written down*. This answers the question that',
        'actually comes up in play and in a change: **what do we know about the house in front',
        'of us?** A house is the unit this world is organised around, and its material is spread',
        'across a catalog entry, a member roll, a grant chain, a relationship table, two or three',
        'docs and a handful of design constants - none of which name each other.',
        '',
        'Counts are mentions, so they rank rather than measure. The first file listed is almost',
        'always the one to read first.',
        '',
        `**The median house is written about in ${median} files**, and the most-written-about,`,
        `the ${worst.name}, in ${worst.mentions.length}. That is the number this file exists for:`,
        'nobody was going to find all of that by grepping, and nobody did - six times in one',
        'session somebody wrote down design that was already in the catalog.',
        '',
        '<!-- BEGIN GENERATED: houses -->',
        ''
    ];
    for (const h of rows) {
        const top = h.mentions.slice(0, 8)
            .map(m => `[\`${m.base}\`](${m.dir === 'docs/world' ? m.base : `../../${m.rel}`}) ${m.n}`)
            .join(' · ');
        lines.push(`### ${h.name}`);
        lines.push('');
        lines.push(`\`${h.id}\` · its entry: [\`sects.ts:${h.line}\`](../../src/data/cultivation/sects.ts)`);
        lines.push('');
        lines.push(`**Read:** ${top || '_nothing outside its own entry_'}`);
        if (h.mentions.length > 8) lines.push(`  …and ${h.mentions.length - 8} more files.`);
        if (h.ranked.length) {
            const shown = h.ranked.slice(0, 6).map(([name]) => `\`${name}\``).join(', ');
            const rest = h.ranked.length > 6 ? `, and ${h.ranked.length - 6} more` : '';
            lines.push('');
            lines.push(`**Constants most about it:** ${shown}${rest}`);
        }
        lines.push('');
    }
    lines.push('<!-- END GENERATED: houses -->');
    return lines.join('\n') + '\n';
}

const isMain = process.argv[1]
    && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
    const next = build();
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (process.argv.includes('--check')) {
        if (next !== current) {
            console.error('docs/world/BY-HOUSE.md is stale. Run: npm run docs:houses');
            process.exit(1);
        }
        console.log('docs/world/BY-HOUSE.md is current.');
    } else {
        fs.writeFileSync(OUT, next);
        console.log(next === current ? 'BY-HOUSE.md unchanged.' : 'BY-HOUSE.md written.');
    }
}
